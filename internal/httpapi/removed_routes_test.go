// TestRemovedRoutesAreNotRegistered asserts that no retired route is in the
// platform's route table. This is the exact check: a route that answers
// method-not-allowed still matches a parameterised route such as
// /api/runners/:id, and only the route table says whether the route itself
// exists.
func TestRemovedRoutesAreNotRegistered(t *testing.T) {
	s, err := repo.OpenTest()
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(s.Close)
	h := New(s, tracker.NewService(), "", "")
	registered := map[string]bool{}
	for _, route := range h.Routes() {
		registered[route.Method+" "+route.Path] = true
	}
	for _, route := range removedRoutes {
		if registered[route.method+" "+route.path] {
			t.Errorf("%s %s is still registered", route.method, route.path)
		}
	}
}

// TestRemovedRoutesDoNotAnswer asserts that a retired route does not answer
// with data. A path that still matches a parameterised route answers
// method-not-allowed, which is the platform saying "no such method here" —
// still no data. A redirect or a success is a surface that came back.
func TestRemovedRoutesDoNotAnswer(t *testing.T) {
	s, err := repo.OpenTest()
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(s.Close)
	h := New(s, tracker.NewService(), "", "")
	for _, route := range removedRoutes {
		if route.method == http.MethodOptions {
			// The CORS preflight answers every path; it says nothing about
			// whether a route exists.
			continue
		}
		req := httptest.NewRequest(route.method, route.path, nil)
		rec := httptest.NewRecorder()
		h.ServeHTTP(rec, req)
		switch rec.Code {
		case http.StatusNotFound, http.StatusMethodNotAllowed:
		default:
			t.Errorf("%s %s answered %d, want not-found", route.method, route.path, rec.Code)
		}
	}
}

// TestRouteSurfaceHoldsOnlyThePersonalRoutes asserts the whole route surface:
// every registered route must be one the personal build keeps. A new surface
// cannot be added without this test noticing.
func TestRouteSurfaceHoldsOnlyThePersonalRoutes(t *testing.T) {
	s, err := repo.OpenTest()
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(s.Close)
	h := New(s, tracker.NewService(), "", "")
	allowed := map[string]bool{}
	for _, route := range personalRoutes {
		allowed[route.method+" "+route.path] = true
	}
	for _, route := range h.Routes() {
		if route.Method == http.MethodOptions {
			// The CORS preflight answers every path; it is not a route.
			continue
		}
		key := route.Method + " " + route.Path
		if !allowed[key] {
			t.Errorf("%s is not part of the personal build's route surface", key)
		}
	}
	for _, route := range personalRoutes {
		key := route.method + " " + route.path
		found := false
		for _, live := range h.Routes() {
			if live.Method+" "+live.Path == key {
				found = true
				break
			}
		}
		if !found {
			t.Errorf("%s should be part of the personal build's route surface", key)
		}
	}
}

